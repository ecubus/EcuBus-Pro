export type PanelLabel = keyof typeof labels

export function usePanelLocale() {
  const language = ref(i18next.language || 'en')
  const changed = (value: string) => {
    language.value = value
  }
  i18next.on('languageChanged', changed)
  onUnmounted(() => i18next.off('languageChanged', changed))
  return (key: PanelLabel) => labels[key][language.value.startsWith('zh') ? 0 : 1]
}
